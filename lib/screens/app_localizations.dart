  static List<String> catalogProblems() {
    final spanish = _localizedValues['es']!.keys.toSet();
    final english = _localizedValues['en']!.keys.toSet();
    final german = _localizedValues['de']!.keys.toSet();
    final problems = <String>[];
    for (final key in spanish.difference(english)) {
      problems.add('falta en inglés: $key');
    }
    for (final key in english.difference(spanish)) {
      problems.add('sobra en inglés: $key');
    }
    for (final key in spanish.difference(german)) {
      problems.add('falta en alemán: $key');
    }
    for (final key in german.difference(spanish)) {
      problems.add('sobra en alemán: $key');
    }
    return problems;
  }

  static bool catalogsMatch() => catalogProblems().isEmpty;

